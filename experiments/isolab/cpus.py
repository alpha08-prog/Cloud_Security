"""CPU placement planner: gives each tenant its own physical cores (R2).

Reads the real core/thread topology of the container host (the Docker Desktop VM
or the CI runner) through a throwaway container, then assigns CPU sets so that
  * the provider plane and the load generator get cores of their own,
  * no two tenants share a physical core (no SMT siblings across tenants),
when the host has enough cores. On small hosts (e.g. a 2-core CI runner) it does
the best it can and records why in PLACEMENT_NOTES; the auditor's XVM-05 check
then reports the sharing honestly instead of hiding it.
"""

from __future__ import annotations

from dataclasses import dataclass, field

from . import util

ENV_FILE = util.TESTBED / "cpus.env"


@dataclass
class Placement:
    logical_cpus: int
    cores: list[list[int]]
    provider: list[int]
    loadgen: list[int]
    tenant: dict[str, list[int]]
    quota: dict[str, float]
    notes: list[str] = field(default_factory=list)

    def env(self) -> dict[str, str]:
        fmt = lambda cpus: ",".join(str(c) for c in sorted(cpus))  # noqa: E731
        return {
            "LOGICAL_CPUS": str(self.logical_cpus),
            "PHYSICAL_CORES": str(len(self.cores)),
            "CPUSET_PROVIDER": fmt(self.provider),
            "CPUSET_LOADGEN": fmt(self.loadgen),
            "CPUSET_TENANT_A": fmt(self.tenant["a"]),
            "CPUSET_TENANT_B": fmt(self.tenant["b"]),
            "CPUSET_TENANT_C": fmt(self.tenant["c"]),
            "CPUS_TENANT_A": f"{self.quota['a']:.1f}",
            "CPUS_TENANT_B": f"{self.quota['b']:.1f}",
            "CPUS_TENANT_C": f"{self.quota['c']:.1f}",
            # The noisy job asks for one worker per logical CPU: in the insecure
            # profile that is the whole host; hardened confines it to tenant-b.
            "STRESS_WORKERS": str(self.logical_cpus),
            "PLACEMENT_NOTES": "; ".join(self.notes) or "each tenant on dedicated physical cores",
        }


def read_topology() -> list[list[int]]:
    """Physical cores as lists of logical CPU ids (SMT siblings grouped)."""
    script = (
        "for c in /sys/devices/system/cpu/cpu[0-9]*; do "
        "echo $(basename $c) $(cat $c/topology/thread_siblings_list 2>/dev/null || basename $c | tr -d cpu); done"
    )
    out = util.docker("run", "--rm", "--label", f"{util.L_PLANE}=operator", util.ALPINE, "sh", "-c", script)
    groups: dict[tuple[int, ...], None] = {}
    for line in out.splitlines():
        parts = line.split()
        if len(parts) < 2:
            continue
        groups[tuple(_expand(parts[1]))] = None
    return sorted((list(g) for g in groups), key=lambda g: g[0])


def _expand(spec: str) -> list[int]:
    cpus: list[int] = []
    for part in spec.split(","):
        if "-" in part:
            lo, hi = part.split("-")
            cpus.extend(range(int(lo), int(hi) + 1))
        elif part.strip():
            cpus.append(int(part))
    return cpus


def plan(cores: list[list[int]]) -> Placement:
    logical = sum(len(c) for c in cores)
    n = len(cores)
    notes: list[str] = []
    if n >= 6:
        provider, loadgen = cores[0], cores[1]
        a, b, c = cores[2], cores[3] + cores[4], cores[5]
    elif n == 5:
        provider, loadgen, a, b, c = cores[0], cores[1], cores[2], cores[3], cores[4]
    elif n == 4:
        provider, loadgen, a, b = cores[0], cores[1], cores[2], cores[3]
        c = cores[0]
        notes.append("tenant-c shares the provider core (4 physical cores)")
    elif n == 3:
        provider = loadgen = cores[0]
        a, b, c = cores[1], cores[2], cores[0]
        notes.append("load generator and tenant-c share the provider core (3 physical cores)")
    else:
        provider = loadgen = c = cores[0]
        rest = cores[1] if n > 1 else cores[0]
        if len(rest) >= 2:
            a, b = rest[:1], rest[1:]
            notes.append("tenant-a and tenant-b are SMT siblings of one physical core (too few cores)")
        else:
            a = b = rest
            notes.append("tenant-a and tenant-b share one CPU (too few cores)")
        notes.append("load generator and tenant-c share the provider core")
    quota = {
        "a": float(len(a)),
        # One thread short of tenant-b's cpuset, so its CPU quota (not just the
        # cpuset) is what caps the noisy job, and throttling shows up in metrics.
        "b": float(max(1, len(b) - 1)) if len(b) > 1 else 1.0,
        "c": 1.0,
    }
    return Placement(logical, cores, list(provider), list(loadgen), {"a": list(a), "b": list(b), "c": list(c)},
                     quota, notes)


def write_env(placement: Placement) -> None:
    lines = ["# Generated by `python scripts/lab.py cpus`. Do not edit; re-run instead."]
    lines += [f"{k}={v}" for k, v in placement.env().items()]
    ENV_FILE.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")


def read_env() -> dict[str, str]:
    if not ENV_FILE.exists():
        return {}
    env = {}
    for line in ENV_FILE.read_text(encoding="utf-8").splitlines():
        if line and not line.startswith("#") and "=" in line:
            key, value = line.split("=", 1)
            env[key] = value
    return env


def ensure() -> dict[str, str]:
    env = read_env()
    if not env:
        placement = plan(read_topology())
        write_env(placement)
        env = read_env()
    return env
