"""Package the completed pilot without large trained-model binaries."""
from pathlib import Path
import shutil
from zipfile import ZipFile, ZIP_DEFLATED

ROOT=Path(__file__).resolve().parents[1]
DEST=ROOT/'docs/research'
SOURCE=ROOT/'results/comparison/pilot01'
shutil.copyfile(SOURCE/'report.md',DEST/'pilot-report.md')
with ZipFile(DEST/'IsoLab_Pilot_Evidence.zip','w',compression=ZIP_DEFLATED,compresslevel=9) as archive:
    for path in sorted(SOURCE.rglob('*')):
        if path.is_file() and path.suffix not in ('.keras','.tmp'):
            archive.write(path,arcname=str(path.relative_to(ROOT)).replace('\\','/'))
    archive.writestr('README-evidence.txt','Extract into the repository root and run python scripts/pilot_publication.py.\nContains measured inputs, splits, predictions and logs; trained .keras binaries remain local and can be regenerated.\n')
